"""Build the macOS native parts (apple/README.md): the Go dispatcher as a C archive, then
SolarisManager.dylib and the system extension from apple/project.yml, with the GEO data
(scripts/fetch_geodata.py) in the extension's resources, then a check app that bundles both
the way Solaris.app does.

    uv run python scripts/build_apple.py          # unsigned: CI, machines without the certificate
    uv run python scripts/build_apple.py --sign   # Developer ID, then verify the signatures

Everything lands in build/apple:

    SolarisManager.dylib
    dev.tschen.solaris.tunnel.systemextension
    check/Solaris.app   the two above in Contents/Frameworks and Contents/Library/SystemExtensions

The check app's executable links every function in SolarisManager.h and never runs;
scripts/build_app.py assembles the real Solaris.app around the Nuitka build. With --sign, Xcode
signs the dylib and the extension (the extension with its profile), the script signs the check
app with the main app's entitlements and profile, and codesign verifies all three. Nothing is
installed or activated: the extension creates a utun, so it only runs on a separate test Mac.
"""

from __future__ import annotations

import argparse
import datetime as dt
import filecmp
import hashlib
import os
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
APPLE = ROOT / "apple"
CORE = ROOT / "src" / "core"
BUILD = ROOT / "build" / "apple"
GEODATA = ROOT / "build" / "geodata"  # scripts/fetch_geodata.py keeps the pinned files here
GEO_FILES = ("GeoSite.dat", "GeoIP.dat")
HEADER = APPLE / "Manager" / "SolarisManager.h"
APP_ENTITLEMENTS = APPLE / "App" / "Solaris.entitlements"
TUNNEL_ENTITLEMENTS = APPLE / "Tunnel" / "SolarisTunnel.entitlements"

TEAM = "GY9ZKZMAZA"
APP_ID = "dev.tschen.solaris"
TUNNEL_ID = "dev.tschen.solaris.tunnel"
APP_PROFILE = "Solaris Developer ID"
TUNNEL_PROFILE = "Solaris Tunnel Developer ID"
ARCH = "arm64"  # D2
DEPLOYMENT_TARGET = "15.0"  # as in apple/project.yml
GOPROXY = "https://goproxy.cn,direct"
GO_VERSION_VARIABLE = "github.com/Ember-Moth/Solaris/src/core/internal/product.Version"
# All four TUN stacks, as on Windows (D3); fd mode defaults to gVisor (docs/architecture.md §3.4).
GO_TAGS = "with_gvisor"
PROFILE_DIRECTORIES = (
    Path.home() / "Library/Developer/Xcode/UserData/Provisioning Profiles",
    Path.home() / "Library/MobileDevice/Provisioning Profiles",
)
# Entitlements that only a provisioning profile can grant (by prefix); the rest need none.
RESTRICTED = (
    "com.apple.developer.",
    "com.apple.application-identifier",
    "com.apple.security.application-groups",
    "keychain-access-groups",
)

MODULE_MAP = """\
// Generated by scripts/build_apple.py. Go's net package calls the resolver in libresolv.
module SolarisCore {
  header "libsolaris.h"
  link "resolv"
  export *
}
"""


class BuildError(Exception):
    pass


@dataclass(frozen=True)
class Profile:
    path: Path
    name: str
    uuid: str
    entitlements: dict[str, Any]
    certificates: frozenset[str]  # SHA-1 of each certificate the profile authorizes


def _run(command: list[str | Path], **options: Any) -> subprocess.CompletedProcess[str]:
    shown = [
        part.relative_to(ROOT) if isinstance(part, Path) and part.is_relative_to(ROOT) else part
        for part in command
    ]
    print("+", " ".join(map(str, shown)), flush=True)
    return subprocess.run([str(part) for part in command], check=True, text=True, **options)


def _output(command: list[str | Path]) -> str:
    arguments = [str(part) for part in command]
    return subprocess.run(arguments, check=True, capture_output=True, text=True).stdout


def _plist(command: list[str | Path]) -> Any:
    arguments = [str(part) for part in command]
    return plistlib.loads(subprocess.run(arguments, check=True, capture_output=True).stdout)


def _remove(path: Path) -> None:
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    else:
        path.unlink(missing_ok=True)


def fetch_geodata() -> None:
    """The pinned GEO data in build/geodata, which project.yml copies into the extension."""
    _run([sys.executable, ROOT / "scripts" / "fetch_geodata.py"], stdout=subprocess.DEVNULL)


def build_go(tags: str, version: str) -> None:
    """The Go dispatcher (src/core/apple) as an arm64 C archive in SolarisCore.xcframework,
    which the extension target links. GetInfo reports ``version`` as the service version."""
    go = BUILD / "go"
    include = go / "include"
    _remove(go)
    include.mkdir(parents=True)
    minimum = f"-mmacosx-version-min={DEPLOYMENT_TARGET}"
    environment = os.environ | {
        "GOPROXY": GOPROXY,
        "CGO_ENABLED": "1",
        "GOOS": "darwin",
        "GOARCH": ARCH,
        "MACOSX_DEPLOYMENT_TARGET": DEPLOYMENT_TARGET,
        "CGO_CFLAGS": minimum,
        "CGO_LDFLAGS": minimum,
    }
    command: list[str | Path] = [
        "go",
        "-C",
        CORE,
        "build",
        "-trimpath",
        "-buildmode=c-archive",
        f"-ldflags=-X {GO_VERSION_VARIABLE}={version}",
    ]
    if tags:
        command += ["-tags", tags]
    _run([*command, "-o", go / "libsolaris.a", "./apple"], env=environment)
    (go / "libsolaris.h").rename(include / "libsolaris.h")
    (include / "module.modulemap").write_text(MODULE_MAP)
    framework = BUILD / "SolarisCore.xcframework"
    _remove(framework)
    _run(
        [
            "xcodebuild",
            "-create-xcframework",
            "-library",
            go / "libsolaris.a",
            "-headers",
            include,
            "-output",
            framework,
        ],
        stdout=subprocess.DEVNULL,
    )


def build_xcode(identity: str | None, version: str, build_number: str) -> Path:
    """Generates Solaris.xcodeproj and builds both targets for Release; returns the products."""
    _run(["xcodegen", "generate", "--spec", APPLE / "project.yml", "--project", APPLE, "--quiet"])
    derived = BUILD / "xcode"
    # Xcode links and signs the products again when they are missing, so that no binary or
    # signature from an earlier build carries over: unsigned after signed, or an interrupted
    # codesign that left a temporary file inside the bundle.
    _remove(derived / "Build" / "Products")
    signing = [f"CODE_SIGN_IDENTITY={identity}"] if identity else ["CODE_SIGNING_ALLOWED=NO"]
    _run(
        [
            "xcodebuild",
            "-project",
            APPLE / "Solaris.xcodeproj",
            "-scheme",
            "Solaris",
            "-configuration",
            "Release",
            "-derivedDataPath",
            derived,
            "-destination",
            "generic/platform=macOS",
            f"MARKETING_VERSION={version}",
            f"CURRENT_PROJECT_VERSION={build_number}",
            *signing,
            "-quiet",
            "build",
        ]
    )
    return derived / "Build" / "Products" / "Release"


def collect(products: Path) -> tuple[Path, Path]:
    dylib = BUILD / "SolarisManager.dylib"
    extension = BUILD / f"{TUNNEL_ID}.systemextension"
    for name, target in (("SolarisManager.dylib", dylib), (extension.name, extension)):
        _remove(target)
        _run(["ditto", products / name, target])
    return dylib, extension


def _declared_functions() -> list[str]:
    return re.findall(r"^(?!//).*?\b(solaris_manager_\w+)\(", HEADER.read_text(), re.MULTILINE)


def check_products(dylib: Path, extension: Path) -> None:
    for binary in (dylib, extension / "Contents" / "MacOS" / TUNNEL_ID):
        architectures = _output(["lipo", "-archs", binary]).split()
        if architectures != [ARCH]:
            raise BuildError(f"{binary.name} is built for {architectures}, not {ARCH} alone")
    exported = {
        line.split()[-1].removeprefix("_")
        for line in _output(["nm", "-gU", dylib]).splitlines()
        if "_solaris_manager_" in line
    }
    declared = set(_declared_functions())
    if exported != declared:
        raise BuildError(
            f"SolarisManager.dylib exports {sorted(exported)}; the header has {sorted(declared)}"
        )
    resources = extension / "Contents" / "Resources"
    for name in GEO_FILES:
        if not filecmp.cmp(resources / name, GEODATA / name, shallow=False):
            raise BuildError(f"the extension's {name} is not the pinned GEO data")
    info = plistlib.loads((extension / "Contents" / "Info.plist").read_bytes())
    expected = {
        "CFBundleIdentifier": TUNNEL_ID,
        "CFBundlePackageType": "SYSX",
        "LSMinimumSystemVersion": DEPLOYMENT_TARGET,
    }
    for key, value in expected.items():
        if info.get(key) != value:
            raise BuildError(f"the extension's {key} is {info.get(key)!r}, not {value!r}")


def assemble_check_app(dylib: Path, extension: Path, version: str, build_number: str) -> Path:
    """The app layout around a stub executable that links every function in the header."""
    app = BUILD / "check" / "Solaris.app"
    _remove(app.parent)
    contents = app / "Contents"
    for directory in ("MacOS", "Frameworks", "Library/SystemExtensions"):
        (contents / directory).mkdir(parents=True)
    _run(["ditto", dylib, contents / "Frameworks" / dylib.name])
    _run(["ditto", extension, contents / "Library" / "SystemExtensions" / extension.name])
    info = {
        "CFBundleExecutable": "Solaris",
        "CFBundleIdentifier": APP_ID,
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleName": "Solaris",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": build_number,
        "LSMinimumSystemVersion": DEPLOYMENT_TARGET,
    }
    (contents / "Info.plist").write_bytes(plistlib.dumps(info))
    functions = ", ".join(f"(void *){name}" for name in _declared_functions())
    stub = BUILD / "check" / "stub.c"
    stub.write_text(
        '#include "SolarisManager.h"\n\n'
        "int main(void) {\n"
        f"  void *functions[] = {{{functions}}};\n"
        "  return functions[0] == 0;\n"
        "}\n"
    )
    _run(
        [
            "xcrun",
            "clang",
            "-arch",
            ARCH,
            f"-mmacosx-version-min={DEPLOYMENT_TARGET}",
            "-I",
            HEADER.parent,
            stub,
            contents / "Frameworks" / dylib.name,
            "-Wl,-rpath,@executable_path/../Frameworks",
            "-o",
            contents / "MacOS" / "Solaris",
        ]
    )
    return app


def find_profile(name: str) -> Profile:
    """The newest unexpired profile of the team with this name, as Xcode picks it."""
    now = dt.datetime.now(dt.UTC)
    found: list[tuple[dt.datetime, Profile]] = []
    for directory in PROFILE_DIRECTORIES:
        for path in sorted(directory.glob("*.provisionprofile")):
            data = _plist(["security", "cms", "-D", "-i", path])
            expires = data["ExpirationDate"].replace(tzinfo=dt.UTC)
            if data["Name"] != name or TEAM not in data["TeamIdentifier"] or expires <= now:
                continue
            certificates = frozenset(
                hashlib.sha1(certificate).hexdigest().upper()
                for certificate in data.get("DeveloperCertificates", [])
            )
            profile = Profile(path, name, data["UUID"], data["Entitlements"], certificates)
            found.append((data["CreationDate"].replace(tzinfo=dt.UTC), profile))
    if not found:
        raise BuildError(f"no valid provisioning profile named {name!r} for team {TEAM}")
    return max(found, key=lambda item: item[0])[1]


def find_identity(profiles: list[Profile]) -> str:
    """SHA-1 of the team's Developer ID Application identity that every profile authorizes."""
    listing = _output(["security", "find-identity", "-v", "-p", "codesigning"])
    pattern = rf'([0-9A-F]{{40}}) "Developer ID Application: [^"]*\({TEAM}\)"'
    usable = set(re.findall(pattern, listing))
    for profile in profiles:
        usable &= profile.certificates
    if not usable:
        raise BuildError(
            f"no Developer ID Application identity of {TEAM} in the keychain is authorized "
            f"by {', '.join(profile.name for profile in profiles)}"
        )
    return sorted(usable)[0]


def sign_check_app(app: Path, identity: str, profile: Profile) -> None:
    shutil.copyfile(profile.path, app / "Contents" / "embedded.provisionprofile")
    _run(
        [
            "codesign",
            "--force",
            "--sign",
            identity,
            "--options",
            "runtime",
            "--timestamp",
            "--entitlements",
            APP_ENTITLEMENTS,
            app,
        ]
    )


def _allows(allowed: Any, value: Any) -> bool:
    """Whether a profile's entitlement value covers the signed one; profiles use * wildcards."""
    if isinstance(value, list):
        return allowed == "*" or (
            isinstance(allowed, list) and all(any(_allows(a, v) for a in allowed) for v in value)
        )
    if isinstance(allowed, str) and isinstance(value, str) and allowed.endswith("*"):
        return value.startswith(allowed[:-1])
    return allowed == value


def _check_signature(code: Path, identity: str) -> None:
    details = subprocess.run(
        ["codesign", "--display", "--verbose=4", str(code)],
        check=True,
        capture_output=True,
        text=True,
    ).stderr
    lines = details.splitlines()
    if f"TeamIdentifier={TEAM}" not in lines:
        raise BuildError(f"{code.name} is not signed by team {TEAM}")
    if not re.search(r"^CodeDirectory .*flags=0x[0-9a-f]+\([^)]*runtime", details, re.MULTILINE):
        raise BuildError(f"{code.name} is signed without the hardened runtime")
    if not any(line.startswith("Timestamp=") for line in lines):
        raise BuildError(f"{code.name} has no secure timestamp")
    with tempfile.TemporaryDirectory() as directory:
        prefix = Path(directory) / "certificate"
        subprocess.run(
            ["codesign", "--display", f"--extract-certificates={prefix}", str(code)],
            check=True,
            capture_output=True,
        )
        leaf = hashlib.sha1(Path(f"{prefix}0").read_bytes()).hexdigest().upper()
    if leaf != identity:
        raise BuildError(f"{code.name} is signed by certificate {leaf}, not {identity}")


def _check_entitlements(bundle: Path, expected_file: Path, profile: Profile) -> dict[str, Any]:
    signed = _plist(["codesign", "--display", "--entitlements", "-", "--xml", bundle])
    expected = plistlib.loads(expected_file.read_bytes())
    if signed != expected:
        raise BuildError(
            f"{bundle.name} is signed with {signed}, not {expected_file.relative_to(ROOT)}"
        )
    for key, value in signed.items():
        if key in profile.entitlements:
            if not _allows(profile.entitlements[key], value):
                raise BuildError(f"{profile.name!r} does not allow {key} = {value!r}")
        elif key.startswith(RESTRICTED):
            raise BuildError(f"{profile.name!r} does not grant {key}")
    embedded = bundle / "Contents" / "embedded.provisionprofile"
    uuid = _plist(["security", "cms", "-D", "-i", embedded])["UUID"]
    if uuid != profile.uuid:
        raise BuildError(f"{bundle.name} embeds profile {uuid}, not {profile.name!r}")
    return signed


def verify(app: Path, identity: str, app_profile: Profile, tunnel_profile: Profile) -> None:
    _run(["codesign", "--verify", "--deep", "--strict", "--verbose=2", app])
    contents = app / "Contents"
    extension = contents / "Library" / "SystemExtensions" / f"{TUNNEL_ID}.systemextension"
    # The app seals Contents/Library/SystemExtensions as resources rather than nested code, so
    # --deep checks the extension's files but not its own signature; verify that separately.
    _run(["codesign", "--verify", "--strict", "--verbose=2", extension])
    for code in (contents / "Frameworks" / "SolarisManager.dylib", extension, app):
        _check_signature(code, identity)
    for bundle, entitlements, profile in (
        (extension, TUNNEL_ENTITLEMENTS, tunnel_profile),
        (app, APP_ENTITLEMENTS, app_profile),
    ):
        signed = _check_entitlements(bundle, entitlements, profile)
        print(f"{bundle.name}: {profile.name} ({profile.uuid}), entitlements {sorted(signed)}")


def _version() -> str:
    return tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the macOS native parts.")
    parser.add_argument(
        "--sign", action="store_true", help="sign with the Developer ID identity and profiles"
    )
    parser.add_argument(
        "--build-number",
        # macOS replaces an activated extension only with another version, so every build
        # gets its own number by default.
        default=dt.datetime.now(dt.UTC).strftime("%Y%m%d.%H%M%S"),
        help="CFBundleVersion (default: the UTC time)",
    )
    parser.add_argument(
        "--tags",
        default=GO_TAGS,
        help=f"Go build tags (default: {GO_TAGS}; docs/architecture.md §3.4)",
    )
    arguments = parser.parse_args()
    if shutil.which("xcodegen") is None:
        sys.exit("build_apple: XcodeGen is missing (brew install xcodegen)")
    version = _version()
    try:
        identity = None
        profiles: tuple[Profile, Profile] | None = None
        if arguments.sign:
            profiles = (find_profile(APP_PROFILE), find_profile(TUNNEL_PROFILE))
            identity = find_identity(list(profiles))
        fetch_geodata()
        build_go(arguments.tags, version)
        products = build_xcode(identity, version, arguments.build_number)
        dylib, extension = collect(products)
        check_products(dylib, extension)
        app = assemble_check_app(dylib, extension, version, arguments.build_number)
        if identity and profiles:
            sign_check_app(app, identity, profiles[0])
            verify(app, identity, *profiles)
    except (BuildError, subprocess.CalledProcessError) as error:
        sys.exit(f"build_apple: {error}")
    print(f"build_apple: {'signed' if identity else 'unsigned'} build in {BUILD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
